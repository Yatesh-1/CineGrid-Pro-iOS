// Generates the Android film fragment-shader (pass 2) body from the WebGL one, so the web preview/stills and the native
// preview/recorder run the same GLSL. Run: node scripts/gen-native-shader.mjs
// Source of truth: src/utils/webglLutPipeline.ts (the block between "Virtual camera film stage" and sample3DLut).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(resolve(root, 'src/utils/webglLutPipeline.ts'), 'utf8').replace(/\r\n/g, '\n');

const start = src.indexOf('// Virtual camera film stage');
const end = src.indexOf('vec4 sample3DLut(');
if (start < 0 || end < 0 || end < start) {
  console.error('film stage markers not found in webglLutPipeline.ts');
  process.exit(1);
}

let block = src.slice(start, end);
// The web shader declares this itself; the native shader declares it with the other main-shader plumbing.
block = block.replace('varying vec2 v_texCoord;\n', '');
// Camera frames arrive as an external OES texture with a rotation/transform matrix: route every image sample
// through srcTex() so the effects can keep working in upright image coordinates.
const before = (block.match(/texture2D\(u_image,/g) || []).length;
block = block.replace(/texture2D\(u_image,/g, 'srcTex(');
if (before === 0) {
  console.error('no u_image samples found; shader layout changed');
  process.exit(1);
}

const header = `#ifdef GL_FRAGMENT_PRECISION_HIGH
precision highp float;
#else
precision mediump float;
#endif
// Pass 2 of the native pipeline. Pass 1 copies the camera's external (YUV) texture ONCE into this ordinary RGBA
// texture, because every sample of the external texture costs a colour conversion and the film stage reads ~35 per pixel.
uniform sampler2D u_image;
varying vec2 v_texCoord; // upright image uv, y = 0 at the top (same convention as the web shader)
vec4 srcTex(vec2 c) {
  return texture2D(u_image, vec2(c.x, 1.0 - c.y)); // the pass-1 texture is stored upright with y up
}
`;
const main = `
void main() {
  vec3 rgb;
  if (u_film > 0.5) {
    rgb = filmColor(filmBase(v_texCoord));
    rgb = filmFinish(rgb, v_texCoord);
  } else {
    rgb = srcTex(v_texCoord).rgb; // unprocessed camera feed
  }
  gl_FragColor = vec4(clamp(rgb, 0.0, 1.0), 1.0);
}
`;

const outPath = resolve(root, 'android/app/src/main/assets/film_fragment.glsl');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, '// GENERATED by scripts/gen-native-shader.mjs from src/utils/webglLutPipeline.ts. Do not edit.\n' + header + block + main);
console.log(`wrote ${outPath} (${before} image samples routed through srcTex)`);
